const EMOJI_RE = /^(?:\p{Extended_Pictographic}|\p{Emoji_Presentation}|\p{Emoji})(?:\uFE0F|\u20E3|\u200D(?:\p{Extended_Pictographic}|\p{Emoji_Presentation}|\p{Emoji}|\p{Emoji_Modifier_Base})|\p{Emoji_Modifier})*$/u;

export function isSingleEmoji(value: string) {
  const s = value.trim();
  if (!s || s.length > 16) return false;
  try {
    return EMOJI_RE.test(s);
  } catch {
    return [...s].length <= 4 && /\p{Emoji}/u.test(s);
  }
}

export function searchEmojis(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return EMOJI_CATS;
  const seen = new Set<string>();
  const hits: { e: string; k: string }[] = [];
  for (const cat of EMOJI_CATS) {
    for (const item of cat.items) {
      if (seen.has(item.e)) continue;
      if (item.e.includes(q) || item.k.includes(q)) {
        seen.add(item.e);
        hits.push(item);
      }
    }
  }
  return hits.length ? [{ name: "検索結果", items: hits }] : [];
}
